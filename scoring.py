import config


def combine_signals(model_score: float, style_score: float) -> float:
    """
    Combine two 0–1 signals into one 0–1 score using conditional split-handling.
    
    Rule:
      - If signals agree closely (diff <= 0.15), use a weighted average.
      - If signals split widely (diff > 0.15), default to the more human-safe 
        (lower) score to minimize false accusations against real people.
    """
    if not 0.0 <= model_score <= 1.0 or not 0.0 <= style_score <= 1.0:
        raise ValueError("Scores must be between 0.0 and 1.0")

    diff = abs(model_score - style_score)
    split_threshold = getattr(config, "SPLIT_THRESHOLD", 0.15)

    if diff > split_threshold:
        # Disagreement split detected: favor the human-safe (lower) score 
        # to prevent false accusations.
        combined = min(model_score, style_score)
    else:
        # Standard weighted average when signals align
        combined = (
            config.WEIGHT_MODEL_SIGNAL * model_score
            + config.WEIGHT_STYLE_SIGNAL * style_score
        )

    return round(min(max(combined, 0.0), 1.0), 4)


def score_to_label(score: float) -> tuple[str, str]:
    """
    Turn a score into a guess and the text a reader actually sees.
    """
    if score < 0.40:
        guess = "human"
        label_text = "We think this was probably written by a person."
    elif score <= 0.60:
        guess = "unsure"
        label_text = "We found mixed signals in this text, and we're not sure who wrote it. If this was flagged by mistake, you can submit an appeal for human review."
    else:
        guess = "ai"
        label_text = "We think this was probably generated by an AI model. If this is an error, please file an appeal."

    return guess, label_text


